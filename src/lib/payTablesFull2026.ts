/**
 * 전체표에서 금액 열 [from, to)(0부터, 호봉 열 제외)만 골라 [호봉, ...금액] 행으로 — 고른 열이 모두 빈 호봉은 뺀다.
 * 예: 경찰 하위 5계급 = pickPayColumns(POLICE_FIRE_PAY_FULL_2026, 0, 5)
 */
export function pickPayColumns(
  rows: ReadonlyArray<ReadonlyArray<number | null>>,
  from: number,
  to: number
): ReadonlyArray<ReadonlyArray<number | null>> {
  return rows
    .map((row) => [row[0], ...row.slice(1 + from, 1 + to)])
    .filter((row) => row.slice(1).some((pay) => typeof pay === "number"));
}

/**
 * 전체표에서 [호봉, 열] 값 조회 — column 은 행 배열 인덱스(1 = 첫 금액 열, 예: 경찰표 1 = 순경).
 * 없는 호봉·열이면 예외(대표 호봉 오기재를 빌드에서 잡는다).
 */
export function payAt(rows: ReadonlyArray<ReadonlyArray<number | null>>, hobong: number, column: number): number {
  const row = rows.find((r) => r[0] === hobong);
  const value = row?.[column];
  if (typeof value !== "number") {
    throw new Error(`[payTablesFull2026] ${hobong}호봉 ${column}열 값이 없습니다`);
  }
  return value;
}
