#!/usr/bin/env node
// scripts/gen-dart-namemap.mjs — 위젯용 회사 id→한글명 경량 맵 코드젠 (2026-08-31, 위젯 B2)
//
// 배경: dartInjection.ts(21KB)에는 한글 회사명이 없어 /widget/company 가 회사명을
// 표기할 수 없다. dartDisclosed.ts(1.3MB)·dartReport 는 위젯 라우트 import 절대
// 금지(번들 폭탄) — 이 스크립트가 회사 데이터 파일에서 id→한글명만 추출해
// src/data/dart/dartNameMap.ts (~8KB) 를 생성한다. 산출물은 커밋 대상.
//
// 규칙:
// - dartInjection 보유 id 만 수록 (위젯이 렌더 가능한 회사만).
// - 별칭 중복 키 제거: src/data/companies/index.ts 의 dedupeCompanies 와 동일하게
//   로드 순서(seedCompanies → Batch2..33 → globalCompanies)에서 id·한글명 기준
//   첫 번째만 유지 — 살아남은 id 만 수록해 /salary-db/{id} 딥링크 유효성을 보장.
//
// 재실행: node scripts/gen-dart-namemap.mjs
//   (dart-etl emit 으로 dartInjection.ts 가 갱신될 때마다 함께 재실행할 것)

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const DATA_DIR = join(ROOT, "src", "data");
const OUT_FILE = join(DATA_DIR, "dart", "dartNameMap.ts");

function log(msg) {
  console.log(`[gen-dart-namemap] ${msg}`);
}
function fail(msg) {
  console.error(`[gen-dart-namemap] ERROR: ${msg}`);
  process.exit(1);
}

// ── 로드 순서: src/data/companies/index.ts 병합 순서와 반드시 일치 ──
const ORDERED_FILES = [
  "seedCompanies.ts",
  ...Array.from({ length: 32 }, (_, i) => `krCompanies_Batch${i + 2}.ts`),
  "globalCompanies.ts",
];

// id 블록 단위 regex 추출 (dart-etl.mjs extractExistingCompanies 와 동일 접근)
function extractCompanies() {
  const companies = [];
  for (const f of ORDERED_FILES) {
    const path = join(DATA_DIR, f);
    if (!existsSync(path)) fail(`데이터 파일 없음: ${f} — index.ts 병합 순서 변경 여부 확인`);
    const src = readFileSync(path, "utf8");
    const idRe = /\bid:\s*"([a-z0-9-]+)"/g;
    let m;
    const ids = [];
    while ((m = idRe.exec(src))) ids.push({ id: m[1], at: m.index });
    for (let i = 0; i < ids.length; i++) {
      const block = src.slice(ids[i].at, ids[i + 1] ? ids[i + 1].at : ids[i].at + 4000);
      const ko = block.match(/ko:\s*"([^"]+)"/)?.[1];
      if (ko) companies.push({ id: ids[i].id, ko });
    }
  }
  return companies;
}

// dedupeCompanies 미러: id·한글명 기준 첫 번째만 유지
function dedupe(companies) {
  const seenId = new Set();
  const seenName = new Set();
  const survivors = new Map(); // id → ko
  for (const c of companies) {
    const nameKey = c.ko.trim();
    if (seenId.has(c.id) || seenName.has(nameKey)) continue;
    seenId.add(c.id);
    seenName.add(nameKey);
    survivors.set(c.id, nameKey);
  }
  return survivors;
}

function readInjectionIds() {
  const injPath = join(DATA_DIR, "dart", "dartInjection.ts");
  if (!existsSync(injPath)) fail("dartInjection.ts 없음 — dart-etl emit 선행 필요");
  const src = readFileSync(injPath, "utf8");
  const start = src.indexOf("dartInjection: Record<string, DartInjectionEntry> = ");
  if (start < 0) fail("dartInjection.ts 형식 인식 실패 (export 선언 변경?)");
  const objStart = src.indexOf("{", start);
  const objEnd = src.lastIndexOf("}");
  const obj = JSON.parse(src.slice(objStart, objEnd + 1));
  return Object.keys(obj);
}

const raw = extractCompanies();
const survivors = dedupe(raw);
const injectionIds = readInjectionIds();

const map = {};
const skippedAlias = [];
const skippedUnknown = [];
for (const id of injectionIds) {
  if (survivors.has(id)) {
    map[id] = survivors.get(id);
  } else if (raw.some((c) => c.id === id)) {
    skippedAlias.push(id); // 데이터엔 있으나 dedupe 에서 탈락 = 별칭 중복 → 정본 id 만 수록
  } else {
    skippedUnknown.push(id); // 회사 데이터에 아예 없음 (corpCodeMap 전용 id 등)
  }
}

const sortedKeys = Object.keys(map).sort();
const sorted = {};
for (const k of sortedKeys) sorted[k] = map[k];

const now = new Date();
const today = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}-${String(now.getDate()).padStart(2, "0")}`;
const body = JSON.stringify(sorted, null, 0);
const ts = `// AUTO-GENERATED by scripts/gen-dart-namemap.mjs — DO NOT EDIT.
// 회사 id → 한글 회사명 (dartInjection 보유분 중 dedupe 생존 정본 id 만 —
// 별칭 중복 키 제거로 /salary-db/{id} 딥링크 유효성 보장).
// 소비자: /widget/company (edge) · /embed 회사 선택기. dartDisclosed(1.3MB)
// 대체용 경량 맵 — 위젯 라우트에는 이 파일 + dartInjection 만 import 할 것.
// 재생성: node scripts/gen-dart-namemap.mjs (기준일: ${today})

export const DART_NAME_MAP_DATE = "${today}";

export const dartNameMap: Record<string, string> = ${body};
`;

if (Buffer.byteLength(ts, "utf8") > 15_000) {
  fail(`산출물 ${Buffer.byteLength(ts, "utf8")}B — 10KB 목표 초과. 수록 기준 재검토 필요`);
}

writeFileSync(OUT_FILE, ts);
log(`dartNameMap.ts: ${sortedKeys.length}곳 (${(Buffer.byteLength(ts, "utf8") / 1024).toFixed(1)}KB) → src/data/dart/dartNameMap.ts`);
log(`별칭 중복 제외 ${skippedAlias.length}건: ${skippedAlias.join(", ") || "없음"}`);
if (skippedUnknown.length) {
  log(`WARN 회사 데이터 미보유 id ${skippedUnknown.length}건 (수록 제외): ${skippedUnknown.join(", ")}`);
}
