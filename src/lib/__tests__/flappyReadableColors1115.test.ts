// GAME OVER·최고 기록·트로피가 파랑 위 파랑(1.0:1)이었다.
// 색 클래스만 바꾼다. 크기·간격·문구·광고는 그대로 — 소스 문자열만 읽는다(렌더·광고 요청 없음).
// 광고 거리 가드는 gameControlAdDistance.test.ts 몫(여기서 고치지 않음).
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const flappy = readFileSync("src/app/fun/flappy/page.tsx", "utf8").replace(/\r\n/g, "\n");

describe("/fun/flappy readable colours", () => {
  it("uses no bg-electric opacity variant (not generated by Tailwind)", () => {
    expect(flappy).not.toMatch(/bg-electric\/\d+/);
  });

  it("GAME OVER, best score and trophy are visible on the blue canvas", () => {
    expect(flappy).toContain('<h2 className="text-4xl font-black text-white mb-2">GAME OVER</h2>');
    expect(flappy).toContain('<span className="text-2xl font-bold text-yellow-300">{highScore}</span>');
    expect(flappy).toContain('<Trophy className="w-16 h-16 text-yellow-300 mb-4" />');
    expect(flappy).not.toMatch(/text-primary[^"]*">GAME OVER/);
    expect(flappy).not.toMatch(/text-primary">\{highScore\}/);
  });

  it("keeps the OF4 A2 bottom padding and the no-ad comment", () => {
    expect(flappy).toMatch(/<main className="[^"]*\bpb-32\b[^"]*"/);
    expect(flappy).toContain("캔버스(탭=점프) 바로 아래에는 광고를 두지 않는다");
  });
});
