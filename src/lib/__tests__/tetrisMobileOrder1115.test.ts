import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const src = readFileSync("src/app/fun/tetris/page.tsx", "utf8").replace(/\r\n/g, "\n");

describe("/fun/tetris readable colours", () => {
  it("uses no bg-electric opacity variant (not generated by Tailwind)", () => {
    expect(src).not.toMatch(/bg-electric\/\d+/);
  });

  it("keeps the solid board container that scopes the overlay text colour", () => {
    expect(src).toContain('<div className="relative bg-electric border-4 border-canvas rounded-lg shadow-2xl overflow-hidden">');
  });

  it("score panels use slate fills with light text, empty cells are slate", () => {
    expect(src).toContain('<div className="bg-slate-900/80 backdrop-blur-md border border-canvas p-6 rounded-2xl shadow-xl">');
    expect(src.match(/<div className="bg-slate-800\/50 p-4 rounded-xl border border-canvas\/50/g)).toHaveLength(3);
    expect(src).toContain('<p className="text-3xl font-bold text-white">{score.toLocaleString(\'ko-KR\')}</p>');
    expect(src).toContain('<p className="text-2xl font-bold text-white">{level}</p>');
    expect(src).toContain('<p className="text-xl font-bold text-white">{highScore.toLocaleString(\'ko-KR\')}</p>');
    expect(src).toContain('className="grid grid-cols-10 grid-rows-20 gap-[1px] bg-slate-800"');
    expect(src).toContain(": 'bg-slate-900'");
    expect(src.match(/aspect-square bg-slate-900\/80 border border-canvas/g)).toHaveLength(4);
  });
});
