//    기본급 10만원 인상·성과급 400%+1320만원·주식 8주·복지포인트 50만원.
//  - 더팩트 2026-09-04 https://news.tf.co.kr/read/ogmeta/2361989.htm: '현대모비스는 … 곧바로 올해 임단협을 마무리했다'.
//  - DART 2026-10-30 주요사항보고서(자기주식처분결정) rcpNo 20261030000571: 처분목적 '2026년 단체교섭에 따른 회사주식 지급',
//    96,136주, 처분 대상 주식가격 353,000원(이사회 결의 전일 2026-10-29 종가), 처분 예정 2026-11-30, 처분 상대방 회사 직원,
//    직원 개인 계좌 입고 또는 우리사주조합 출연(4년 의무예탁) 중 선택.
// 접힌 답(details)은 닫힌 상태의 높이에 영향이 없다. 찬반투표 찬성률은 보도를 찾지 못해 쓰지 않는다.
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";

const page = readFileSync(resolve(process.cwd(), "src/app/calc/hyundai-mobis-bonus/page.tsx"), "utf8").replace(/\s+/g, " ");

describe("모비스 2026 임단협 — 접힌 FAQ 답은 보도·공시 기준 타결", () => {
  it("'언제 결정되나요' 답: 협상 중·반영 전 문구 대신 매체·날짜를 붙인 타결 사실과 DART 공시", () => {
    expect(page).toContain("2026년분은 이미 타결됐습니다.");
    expect(page).toContain(
      "더팩트 2026-08-26 보도에 따르면 모비스 노사는 기본급 10만원 인상, 성과급 400%+1,320만원, 주식 8주, 복지포인트 50만원을 담은 잠정합의안을 마련했고, 더팩트 2026-09-04 보도에 따르면 곧바로 올해 임단협을 마무리했습니다."
    );
    expect(page).toContain("2026-10-30 DART 주요사항보고서(자기주식 처분 결정)");
    expect(page).toContain("96,136주를 2026-11-30 직원에게 처분할 예정이라고 공시했습니다");
    for (const s of ["2026-09-26 기준 찬반투표 결과 보도는 확인되지 않았습니다", "본 계산기에는 아직 반영하지 않았습니다"]) {
      expect(page.includes(s), s).toBe(false);
    }
  });

  it("주식 답: 공시 처분가는 전날 종가, 받는 방식 두 가지와 우리사주조합 4년 의무예탁 — 독자 안내 구절은 그대로", () => {
    expect(page).toContain("처분가 353,000원은 이사회 전날(10월 29일) 종가 기준이라 실제 지급일 주가와 다를 수 있습니다");
    expect(page).toContain("직원 개인 증권계좌로 받거나 우리사주조합에 출연하는 방식 중 하나로 지급되고, 우리사주조합에 출연한 주식은 4년 동안 의무예탁됩니다");
    // publicSourceWording.test.ts ALLOWED 의 정확한 구절
    expect(page).toContain("인출 가능 시점을 사내 공지로 확인하세요");
  });

  it("현대차 비교 답: 2026년은 둘 다 400%, 정액·주식 수는 보도값", () => {
    expect(page).toContain(
      "2026년에는 둘 다 성과금 400%로 같고, 정액은 현대차 1,270만원·모비스 1,320만원, 주식은 현대차 15주·모비스 8주입니다(머니투데이·한국경제 2026-09-01, 더팩트 2026-08-26 보도)."
    );
  });
});
